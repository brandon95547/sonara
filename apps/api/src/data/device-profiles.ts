import { STANDARD_RANGES, type DeviceProfile } from '@sonara/shared'

/**
 * Built-in MIDI controller profiles.
 *
 * These exist so that plugging a keyboard in configures the app rather than
 * presenting the player with a form. A profile carries two things a product
 * name cannot: the manufacturer's identity, and the velocity curve that suits
 * the action.
 *
 * ## Priority
 *
 * Higher is checked first. The bands are deliberate:
 *
 *   80-90  a specific model line   (Yamaha P-series, Roland FP)
 *   60-79  a product family        (Launchkey, Keystation, MPK)
 *   10-30  a shape-of-the-name guess (anything reporting itself as a "digital piano")
 *
 * ## `keyCountFromName`
 *
 * True for families that put the size in the name, so one row covers the whole
 * range of sizes. False where the model number merely contains digits.
 */

const p = (
  profile: Omit<DeviceProfile, 'range'> & { range?: DeviceProfile['range'] },
): DeviceProfile => ({
  ...profile,
  range: profile.range ?? STANDARD_RANGES[profile.keyCount],
})

